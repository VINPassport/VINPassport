/**
 * Where a surface gets ledger state: one function, three backings, tried in
 * that order because each is more authoritative than the next.
 *
 *   server  `npm run app` is running: /api/ledger serves the live in-process
 *           ledger, and everything submitted through the console shows up.
 *           Shared between everyone pointed at that server.
 *   local   no server, but this tab registered a vehicle: the intake console
 *           ran the compiled circuits here and left the resulting ledger in
 *           sessionStorage. Real circuit output, visible to nobody else, and
 *           gone when the tab closes. See local-ledger.mjs.
 *   static  neither: the committed demo export, generated by the same
 *           compiled circuits when the site was built.
 *
 * The surfaces do not care which they got; the shape is identical, because
 * all three are written by the same export code. `mode` is surfaced so a
 * page can label itself honestly - and it must, because "a record in your
 * tab" and "a record on a server" are different claims and only one of them
 * is true at a time. `?src=demo` forces the static path, for reproducible
 * screenshots and as the way back out of a local ledger.
 *
 * SPDX-License-Identifier: Apache-2.0
 */
import { loadLocalLedger } from './local-ledger.mjs';

const fetchJson = async (url) => {
    const r = await fetch(url, { cache: 'no-store' });
    if (!r.ok) throw new Error(`could not load ${url} (${r.status})`);
    return r.json();
};

/**
 * Where /api/ lives for this page: '' when the page is served by the app
 * server itself (npm run app), else whatever host the page names, else null.
 * Resolved once per page load.
 *
 * EVERY PROBE HAS A DEADLINE. A page that waits on a host which is not
 * answering is a page that looks broken, and the static export below is a
 * complete answer, so there is nothing to gain by waiting longer than it takes
 * to find out. Without a deadline the wait is the browser's connection
 * timeout, which is tens of seconds, and it is spent before anything renders.
 *
 * No host is named here. A hosted demo API is the page's choice, declared as
 *
 *   <meta name="vinpassport-api" content="https://…">
 *
 * so that retiring one is an edit to the page that used it rather than a
 * constant in a shared module which every surface then waits on.
 */
const PROBE_TIMEOUT_MS = 2000;

/** The API host this page names, if any. */
export function namedApiBase() {
    const meta = document.querySelector('meta[name="vinpassport-api"]');
    const value = meta?.getAttribute('content')?.trim();
    return value || null;
}

const probe = async (base) => {
    const ctl = new AbortController();
    let timer;
    // The deadline is a RACE as well as an abort. Aborting asks fetch to stop
    // and is the part that frees the connection, but it only bounds the wait
    // if fetch honours the signal. Racing bounds it either way, which is the
    // property that matters: this runs before anything renders.
    const deadline = new Promise((resolve) => {
        timer = setTimeout(() => { ctl.abort(); resolve(false); }, PROBE_TIMEOUT_MS);
    });
    try {
        return await Promise.race([
            fetch(`${base}/api/health`, { cache: 'no-store', signal: ctl.signal })
                .then((r) => r.ok, () => false),   // unreachable, refused, or aborted
            deadline
        ]);
    } finally {
        clearTimeout(timer);
    }
};

let apiBasePromise;
export function resolveApiBase() {
    apiBasePromise ??= (async () => {
        for (const base of ['', namedApiBase()]) {
            if (base === null) continue;
            if (await probe(base)) return base;
        }
        return null;
    })();
    return apiBasePromise;
}

/**
 * `staticBase` is the relative path from the calling page to the scan root,
 * where the static exports live: '' for the scan page, '../' for /console/
 * and /proofs/.
 */
export async function loadState(staticBase = '', params = new URLSearchParams()) {
    if (params.get('src') !== 'demo') {
        try {
            const apiBase = await resolveApiBase();
            if (apiBase != null) {
                const { ledger, vocabulary } = await fetchJson(`${apiBase}/api/ledger`);
                const badge = apiBase === ''
                    ? 'live: compiled circuits, ledger held by this server'
                    : `live: compiled circuits, shared demo ledger at ${apiBase.replace(/^https?:\/\//, '')}`;
                return { ledger, vocabulary, mode: 'server', badge };
            }
        } catch { /* no server: fall through to what this browser holds */ }

        // Nothing answered, so a vehicle this tab registered is the most
        // current record there is. Still behind `src=demo`, which stays the
        // way back out to the canned data.
        const local = loadLocalLedger();
        if (local) {
            const vocabulary = await fetchJson(`${staticBase}fields.json`);
            return {
                ledger: local.ledger, vocabulary, mode: 'local',
                badge: 'added in this browser: the compiled circuits ran in this tab, '
                    + 'and this record exists nowhere else'
            };
        }
    }
    const [ledger, vocabulary] = await Promise.all([
        fetchJson(`${staticBase}demo-data.json`),
        fetchJson(`${staticBase}fields.json`)
    ]);
    return {
        ledger, vocabulary, mode: 'static',
        badge: 'demo ledger, generated by the compiled contract, not read from chain'
    };
}
