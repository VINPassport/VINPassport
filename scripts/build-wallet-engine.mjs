/**
 * Build what the wallet page (site/wallet/) needs, from the build and the
 * deploy record, so nothing on it is hand-copied:
 *
 *   npm run build:wallet              write everything below
 *   npm run build:wallet -- --check   rebuild to a temp dir and compare (CI)
 *
 *   site/assets/wallet-engine/   scripts/lib/wallet-browser.mjs bundled for the
 *                                browser (Midnight.js 5, the DApp Connector
 *                                providers, the compiled contract, ledger wasm)
 *   site/zk/vinpassport/         the circuit artifacts for the circuits the page
 *                                offers (OFFERED in wallet-browser.mjs): keys,
 *                                ZKIR, and the compiler's manifest that every
 *                                artifact is checked against in the browser
 *   site/wallet/config.json      network, contract address, the manifest hash
 *                                the deploy record pins, and a sample vehicle
 *                                key (the recorded run's, public on chain)
 *
 * The output is committed for the reason the intake engine's is (see
 * scripts/build-intake-engine.mjs): the site is served as written, with no
 * build step. --check is what keeps it honest.
 *
 * SPDX-License-Identifier: Apache-2.0
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, mkdtempSync, rmSync, copyFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';
import { tmpdir } from 'node:os';
import { OFFERED } from './lib/wallet-browser.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BUILD_DIR = join(ROOT, 'contracts', 'vinpassport', 'src', 'managed', 'vinpassport');
const NETWORK = 'preview';
const CHECK = process.argv.includes('--check');

const OUT = {
    engine: join(ROOT, 'site', 'assets', 'wallet-engine'),
    zk: join(ROOT, 'site', 'zk', 'vinpassport'),
    config: join(ROOT, 'site', 'wallet', 'config.json')
};

const walk = (dir) => (existsSync(dir) ? readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
}) : []);
/** Every file under `dir`, by relative path, as a content hash. */
const fingerprint = (dir) => Object.fromEntries(walk(dir).sort().map((p) => [
    relative(dir, p).split('\\').join('/'),
    createHash('sha256').update(readFileSync(p)).digest('hex').slice(0, 16)
]));

async function buildInto(base) {
    // 1. The circuit artifacts the page offers, and the manifest they are checked against.
    const zk = join(base, 'zk');
    const files = [
        'compiler/contract-info.json',
        'compiler/contract-manifest.json',
        ...OFFERED.flatMap((c) => [`keys/${c}.prover`, `keys/${c}.verifier`, `zkir/${c}.bzkir`])
    ];
    // Prover keys are not committed, so a fresh checkout (CI) has none in the
    // build. There the served copy stands in, but only if its sha256 is the one
    // the committed compiler manifest records: the check the browser makes.
    const manifestTree = JSON.parse(readFileSync(join(BUILD_DIR, 'compiler', 'contract-manifest.json'), 'utf8'));
    const manifestHash = (f) => f.split('/').reduce((node, part) => node?.[part], manifestTree)?.hash;
    for (const f of files) {
        let from = join(BUILD_DIR, f);
        if (!existsSync(from)) {
            const served = join(OUT.zk, f);
            const ok = existsSync(served) && createHash('sha256').update(readFileSync(served)).digest('hex') === manifestHash(f);
            if (!ok) throw new Error(`${relative(ROOT, from)} is missing, and no served copy matches the manifest: compile with keys first (npm run compile, in WSL)`);
            from = served;
        }
        mkdirSync(dirname(join(zk, f)), { recursive: true });
        copyFileSync(from, join(zk, f));
    }

    // 2. What the page needs to know, from the deploy record and the recording.
    const record = JSON.parse(readFileSync(join(ROOT, 'deploy', `${NETWORK}.json`), 'utf8'));
    const recording = JSON.parse(readFileSync(join(ROOT, 'site', 'demo', `recorded-run.${NETWORK}.json`), 'utf8'));
    const manifest = createHash('sha256').update(readFileSync(join(BUILD_DIR, 'compiler', 'contract-manifest.json'))).digest('hex');
    if (record.build?.manifestSha256 !== manifest) {
        throw new Error('the build on disk is not the build the deploy record pins (manifest hash differs)');
    }
    const config = {
        note: 'Generated by scripts/build-wallet-engine.mjs from deploy/preview.json and the recorded run. Public data only.',
        network: NETWORK,
        contractAddress: record.contractAddress,
        manifestSha256: manifest,
        offered: OFFERED,
        sampleVehicleKey: recording.contractAddress === record.contractAddress ? recording.vinHash : null
    };
    mkdirSync(join(base, 'config'), { recursive: true });
    writeFileSync(join(base, 'config', 'config.json'), JSON.stringify(config, null, 2) + '\n');

    // 3. The bundle.
    const { build } = await import('vite');
    await build({
        logLevel: 'warn',
        base: './',
        build: {
            outDir: join(base, 'engine'),
            emptyOutDir: true,
            target: 'es2022',
            assetsInlineLimit: 0,
            rollupOptions: {
                input: join(ROOT, 'scripts', 'lib', 'wallet-browser.mjs'),
                preserveEntrySignatures: 'strict',
                // Content-hashed names: the bundle holds two wasm files with the
                // same base name (two onchain-runtime versions), and without a
                // hash they were numbered in whatever order the bundler met them,
                // which changed between builds and broke --check.
                output: { format: 'es', entryFileNames: 'wallet-engine.js', chunkFileNames: '[name]-[hash].js', assetFileNames: '[name]-[hash][extname]' }
            }
        }
    });
}

const tmp = mkdtempSync(join(tmpdir(), 'vinpassport-wallet-'));
try {
    await buildInto(tmp);
    const fresh = {
        engine: fingerprint(join(tmp, 'engine')),
        zk: fingerprint(join(tmp, 'zk')),
        config: fingerprint(join(tmp, 'config'))
    };
    if (!CHECK) {
        for (const k of ['engine', 'zk']) {
            rmSync(OUT[k], { recursive: true, force: true });
            mkdirSync(OUT[k], { recursive: true });
            for (const f of Object.keys(fresh[k])) {
                mkdirSync(dirname(join(OUT[k], f)), { recursive: true });
                copyFileSync(join(tmp, k, f), join(OUT[k], f));
            }
        }
        mkdirSync(dirname(OUT.config), { recursive: true });
        copyFileSync(join(tmp, 'config', 'config.json'), OUT.config);
        for (const k of ['engine', 'zk']) for (const [f, h] of Object.entries(fresh[k])) console.log(`  ${h}  ${k}/${f}`);
        console.log(`  ${fresh.config['config.json']}  wallet/config.json`);
        console.log('\nbuild:wallet: written');
    } else {
        const committed = {
            engine: fingerprint(OUT.engine),
            zk: fingerprint(OUT.zk),
            config: existsSync(OUT.config) ? { 'config.json': fingerprint(dirname(OUT.config))['config.json'] } : {}
        };
        let drift = 0;
        for (const k of ['engine', 'zk', 'config']) {
            for (const f of [...new Set([...Object.keys(fresh[k]), ...Object.keys(committed[k])])].sort()) {
                const same = fresh[k][f] === committed[k][f];
                if (!same) drift += 1;
                console.log(`  ${same ? 'same ' : 'DRIFT'}  ${k}/${f}`);
            }
        }
        if (drift) {
            console.error('\ncheck: the committed wallet page assets are not what the build and the deploy record produce.');
            console.error('Run `npm run build:wallet` and commit the result.');
            process.exitCode = 1;
        } else {
            console.log('\ncheck: the wallet page assets match the build and the deploy record');
        }
    }
} finally {
    rmSync(tmp, { recursive: true, force: true });
}
